"""知识点**别名表**（D4）：让「COPD」与「慢性阻塞性肺疾病」互相召回。

## 为什么需要它

`core/errsearch.py` 的召回是**子串匹配**（`查询token in 归一文本`），
而「缩写/简称 ↔ 全称」通常**不是**子串关系：

| 查询 | 记录里写的是 | 子串命中？ | 需要别名表？ |
|---|---|---|---|
| `心衰` | `心力衰竭` | ❌ **否**（前两字是「心力」） | **是** |
| `湿啰音` | `中细湿啰音` | ✅ 是 | 否 |
| `心肌梗死` | `急性心肌梗死` | ✅ 是（单向） | 否（但同组仍增加反向召回） |
| `COPD` | `慢性阻塞性肺疾病` | ❌ 否 | **是** |
| `慢阻肺` | `慢性阻塞性肺疾病` | ❌ 否 | **是** |

> ⚠️ **2026-10-02 实测勘误**：本文档与 `errsearch.py`、`db.fts_tokens` 此前都把
> `心衰 → 心力衰竭` 记成「子串能命中，不需别名表」——**这是错的**。
> `"心衰" in "心力衰竭"` 实测为 **False**（`心衰` 不是前缀也不是子串）。
> 之所以有时「看起来能中」，是因为文本里**恰好也写了「心衰」**（两写法同现），
> 不是因为子串匹配。⇒ `心衰` 恰是别名表要解决的**典型**场景。
> 教训与 `errsearch` 文末留档同源：**「例子能跑通」≠「是我说的那个机制让它跑通的」**。

## 双向展开（关键设计）

别名必须**对称**展开，否则只能半工：记录写全称、用户查缩写能中，
反过来（记录写缩写、用户查全称）就中不了。故本表存**等价组**，
`expand()` 对任意成员都返回同组全部成员。

## 覆盖率语义（为什么不能简单"追加 token"）

`errsearch.search` 的排序是 `覆盖率 = 命中组数 / 总组数`。
若把 `COPD` 直接展开成 `["copd", "慢性阻塞性肺疾病", ...]` 追加进 token 列表，
**总 token 数会变大** ⇒ 一个只因主词命中的记录覆盖率被**稀释**，排序反而变差。

故本模块返回的是**等价组**（`list[list[str]]`），由 `errsearch` 按
「**同组任一成员命中即算该组命中**」来计覆盖率——组作为一个整体参与，
不改变总词组数。这是本模块与 `query_tokens()` 的**接口契约**，改之前先读 `search()`。

## 收录判据（三条都要满足）

1. 指向**同一个知识点**（不是相关知识点）；
2. 成员进来能**新增召回面**（见 `tests/test_kp_aliases.py::test_no_member_is_prefix_shadowed`）
   ——与同组其他成员**互为子串**（本质重复）的不许收；
3. 都是用户在**检索框里真会打的**形态（缩写 / 常用简称）。

> 注意「同组含**单向**子串」是**允许且常见**的（`心肌梗死` ⊂ `急性心肌梗死`）：
> 短方能命中长文本，但长方的查询命中不了只写短方的文本 ⇒ 同组仍增加方向性召回。

## 边界（有意为之）

- **只做词表映射，不做语义相似**（「肺炎」↔「肺部感染」这种不属于别名，属语义检索）。
- **表是种子，不是全集**：真实用户的常用表述要靠使用中积累（D4 原意）。
  表在 `_GROUPS` 里，新增一组只需加一行；`tests/test_kp_aliases.py` 锁住结构性质
  （对称性 / 无冗余 / 无自映射）而非字面条目数。
- **不落库、不建索引**：与 `errsearch` 同一理由（见该模块 docstring）——
  纯内存常量表零成本、零漂移。
"""

from __future__ import annotations

import re

__all__ = ["ALIAS_GROUPS", "expand", "alias_of", "match_query"]

_WS_RE = re.compile(r"\s+")

# 等价组：组内任意两个成员互相是别名（对称闭包由 `expand()` 保证，这里只写代表元）。
#
# 收录判据（三条都要满足）：
#   ① 指向**同一个知识点**（不是相关知识点）；
#   ② 新增召回面——**不得含同组其他成员为子串**（含者冗余：它的召回面是对方的子集）；
#   ③ 都是用户在**检索框里真会打的**形态（缩写 / 常用简称）。
#
# ⚠️ 判据②的**正确形态**（我第一版写错过两次，见 `tests/test_kp_aliases.py` 留档）：
#   「A 含 B 为子串」⟹ A 的召回面 ⊆ B 的召回面 ⟹ **A 冗余**（反之不然）。
#   - `心肌梗死` ⊂ `急性心肌梗死` ⇒ **删「急性心肌梗死」**（保留短串）：短串能命中长文本。
#   - `心衰` ⊄ `心力衰竭`（前两字是「心力」）⇒ 两者都留（各命中对方命不中的文本）。
#
# 排序：按首组成员，便于人工核对与 diff。
ALIAS_GROUPS: tuple[tuple[str, ...], ...] = (
    # ---- 呼吸 ----
    ("copd", "慢阻肺", "慢性阻塞性肺疾病"),
    ("ards", "急性呼吸窘迫综合征", "急性呼吸窘迫综合症"),
    ("osa", "阻塞性睡眠呼吸暂停", "睡眠呼吸暂停低通气综合征"),
    # ---- 循环 ----
    ("ami", "心肌梗死", "心梗"),
    ("acs", "急性冠脉综合征", "急性冠状动脉综合征"),
    # 心衰 / 心力衰竭：`心衰` **不是** `心力衰竭` 的子串（前两字是「心力」）——
    # 2026-10-02 实测 `"心衰" in "心力衰竭"` 为 **False**，此前多处文档写成 True，已勘误。
    # ⇒ 这正是别名表的**典型**场景。
    ("chf", "心力衰竭", "心衰", "心功能不全"),
    ("af", "房颤", "心房纤颤"),
    ("htn", "高血压"),
    # ---- 内分泌 ----
    ("dm", "糖尿病"),
    ("t2dm", "2型糖尿病", "二型糖尿病", "2 型糖尿病"),
    ("dka", "酮症酸中毒"),
    # ---- 神经 ----
    ("cva", "脑卒中", "脑血管意外", "中风"),
    ("tia", "短暂性脑缺血发作", "一过性脑缺血发作"),
    # ---- 消化 ----
    ("gerd", "胃食管反流", "反流性食管炎"),
    ("ibs", "肠易激综合征", "肠易激综合症"),
    # ---- 泌尿 ----
    ("ckd", "慢性肾脏病", "慢性肾病"),
    ("aki", "急性肾损伤", "急性肾衰竭"),
    ("uti", "尿路感染", "泌尿系感染"),
    # ---- 血液 ----
    ("ida", "缺铁性贫血", "缺铁贫"),
    ("dvt", "深静脉血栓"),
    # ---- 感染 ----
    ("hbv", "乙型肝炎", "乙肝"),
    ("hcv", "丙型肝炎", "丙肝"),
    ("tb", "肺结核", "结核病"),
    # ---- 妇产 ----
    ("gdm", "妊娠期糖尿病", "妊娠糖尿病"),
    ("pcos", "多囊卵巢综合征", "多囊卵巢综合症"),
)

# 归一化（小写 + 去空白）后的 「成员 → 所属组」索引（模块级预计算，避免每次查询重扫）。
_INDEX: dict[str, int] = {}
for _gi, _group in enumerate(ALIAS_GROUPS):
    for _member in _group:
        _key = _member.strip().lower()
        # 结构守卫（tests/test_kp_aliases.py）会钉住这两条；这里 fail-fast 更早暴露手误。
        if not _key:
            raise ValueError(f"ALIAS_GROUPS[{_gi}] 含空成员")
        if _key in _INDEX:
            raise ValueError(
                f"别名成员 {_member!r} 同时出现在组 {_INDEX[_key]} 与组 {_gi}"
                "——同一词只能属于一个等价组（否则展开歧义）")
        _INDEX[_key] = _gi


def alias_of(term: str) -> tuple[str, ...]:
    """返回 `term` 所属的**等价组**（含自身，归一为小写）；无别名 → 只含自身的元组。

    返回元组保证调用方不会意外改到共享常量。
    """
    key = (term or "").strip().lower()
    gi = _INDEX.get(key)
    if gi is None:
        return ((term or "").strip(),) if (term or "").strip() else ()
    return ALIAS_GROUPS[gi]


def expand(terms: list[str]) -> list[list[str]]:
    """把查询 token 列表转成**等价组列表**（每个元素是「同义成员」的集合）。

    契约（`errsearch.search` 依赖）：
      - **保序**：输出与输入等长、逐位对应（无别名的 token → 单元素组）；
      - **去重**：同一等价组只出现一次（多个 token 落同组时后者被丢弃）；
      - **组内不含空串**，且**首元素可以是归一前的原词**（保持片段定位可用）。

    为什么返回 `list[list[str]]` 而不是拍平：见模块 docstring「覆盖率语义」。
    """
    out: list[list[str]] = []
    seen_groups: set[int] = set()
    for t in terms:
        key = (t or "").strip().lower()
        gi = _INDEX.get(key)
        if gi is None:
            out.append([t])
            continue
        if gi in seen_groups:          # 同组多 token ⇒ 只保留一次（避免重复计覆盖率）
            continue
        seen_groups.add(gi)
        out.append(list(ALIAS_GROUPS[gi]))
    return out


def match_query(query: str) -> list[str] | None:
    """整串查询是否命中别名表 → 返回该等价组；否则 `None`。

    ## 为什么必须**在分词之前**做整串匹配（2026-10-02 实测暴露）

    `query_tokens()` 走 `db.fts_tokens()`（jieba 词 + CJK 二元组），
   **会把别名词切碎**：

    | 查询 | `query_tokens` 产出 | 逐 token 查表 | 结果 |
    |---|---|---|---|
    | `COPD` | `['copd']` | 命中 | ✅（ASCII 不切） |
    | `慢阻肺` | `['慢阻', '阻肺']` | **都不命中** | ❌ 别名被 jieba 切开 |
    | `心梗` | `['心梗']` | 命中 | ✅ |

    ⇒ 逐 token 查表对**纯 ASCII 缩写**有效，对**中文简称**无效（会被 jieba 切开）。
    故 `query_tokens` 先拿**归一后的整串**来 `match_query`：
    命中 ⇒ **打头放整组**（整串本身进不了 `fts_tokens` 时 token 为空，正需要它兜底）；
    未命中 ⇒ 走原分词。
    """
    key = _WS_RE.sub("", (query or "").lower())
    if not key:
        return None
    gi = _INDEX.get(key)
    return list(ALIAS_GROUPS[gi]) if gi is not None else None
